"""Generate Lightlike/TuraevViro/Reflect/RacahCert<k>.lean for each Z-power k.
Reads parts.pkl (from size2.py): Dc, the numerators N1,N3,N5 of c1,c3,c5, and the polynomials n_{k,*}.
Per k, each of the four products (Dc*n0, N1*n1, N3*n3, N5*n5) is checked against its normal form
(small kernel run), then the sum of the four normal forms is checked to be empty. This keeps each
kernel computation small. Run from scripts/qracah with parts.pkl present."""
import pickle, sympy as sp, sys
import chunk  # splits long list literals (see chunk.py); the generated files carry no heartbeat cap
Dc,Ns,res=pickle.load(open('parts.pkl','rb'))
gens=sp.symbols("u p1 p2 p3 p4 q2 q3")
def P(e): return sp.Poly(sp.sympify(e),*gens)
def lit(p):
    return "[" + ", ".join(f"(⟨{m[0]}, {m[1]}, {m[2]}, {m[3]}, {m[4]}, {m[5]}, {m[6]}, 0⟩, {int(c)})" for m,c in sorted(p.terms())) + "]"
for k in sorted(res):
    v=res[k]
    items=[("D0","n0",P(Dc),P(v[(0,0,0)]))]
    for i,cc in ((1,(1,0,0)),(3,(0,1,0)),(5,(0,0,1))):
        if cc in v: items.append((f"N{i}",f"n{i}",P(Ns[(i-1)//2]),P(v[cc])))
    out=f"""import Lightlike.TuraevViro.Reflect.Poly

/-!
# Coefficient identity of `Z^{k}` of the q-Racah recurrence certificate

`Dc * n0 + N1 * n1 + N3 * n3 + N5 * n5 = 0` as reflected polynomials (`Poly.lean`): each product is
checked against its normal form `Y_i`, then the sum of the `Y_i` is checked to be empty, all by
`decide +kernel`. `coeff{k}` is the resulting identity of the evaluations in any field. Generated by
`scripts/qracah/gen_cert.py`.
-/

set_option maxRecDepth 100000

namespace Lightlike.TV.Refl
"""
    ys=[];prods=[]
    for j,(a,b,pa,pb) in enumerate(items):
        nm_a=f"A{k}_{j}"; nm_b=f"B{k}_{j}"; nm_y=f"Y{k}_{j}"
        out+=f"def {nm_a} : Poly := {lit(pa)}\ndef {nm_b} : Poly := {lit(pb)}\ndef {nm_y} : Poly := {lit(sp.Poly(pa.as_expr()*pb.as_expr(),*gens))}\n"
        out+=f"theorem prod{k}_{j} : mul {nm_a} {nm_b} = {nm_y} := by decide +kernel\n"
        ys.append(nm_y);prods.append((nm_a,nm_b))
    s=ys[0]
    for y in ys[1:]: s=f"(add {s} {y})"
    out+=f"theorem sum{k} : ({s}).isEmpty = true := by decide +kernel\n\n"
    out+=f"/-- The coefficient identity of `Z^{k}`, in any field. -/\ntheorem coeff{k} {{K : Type*}} [Field K] {{E : Env K}} (hE : E.NZ) :\n    "
    out+=" + ".join(f"Poly.eval E {a} * Poly.eval E {b}" for a,b in prods)+" = 0 := by\n"
    out+="  simp only ["+", ".join(f"← eval_mul hE, prod{k}_{j}" for j in range(len(items)))+"]\n"
    out+="  rw ["+", ".join(f"← eval_add" for _ in range(len(items)-1))+"]\n" if False else ""
    # build by explicit steps
    out=out.rsplit("  simp only [",1)[0]
    steps="".join(f"  rw [← eval_mul hE, prod{k}_{j}]\n" for j in range(len(items)))
    out+=steps
    out+="  rw ["+", ".join(["← eval_add"]*(len(items)-1))+"]\n"
    out+=f"  have h := sum{k}\n  rw [List.isEmpty_iff] at h\n  rw [h]; rfl\n\n"
    out+="end Lightlike.TV.Refl\n"
    open(f"../../Lightlike/TuraevViro/Reflect/RacahCert{k}.lean","w").write(chunk.rewrite(out))
print(sorted(res))
