"""Generate Lightlike/TuraevViro/Reflect/RacahEval.lean: values of the product factors fQ0..fW1 of the
cleared recurrence as bracket products in a field. Needs facs.out (a JSON file written by gen_core.py)."""
import json, os, re
F=json.load(open("facs.out"))
NAMES=["u","p1","p2","p3","p4","q2","q3","Z"]
def mono(v):
    fs=[]
    for n,e in zip(NAMES,v):
        if e==0: continue
        if e==1: fs.append(n)
        elif e==-1: fs.append(f"{n}⁻¹")
        elif e>0: fs.append(f"{n}^{e}")
        else: fs.append(f"({n}^{-e})⁻¹")
    return " * ".join(fs) if fs else "1"
def parse(t):
    toks=re.findall(r"\(|\)|\[|\]|⟨[^⟩]*⟩|[a-z]+|-?\d+|,",t); pos=[0]
    vec=lambda x: tuple(int(v) for v in x[1:-1].split(","))
    def go():
        x=toks[pos[0]]
        if x=="[":
            pos[0]+=1; terms=[]
            while toks[pos[0]]!="]":
                if toks[pos[0]]==",": pos[0]+=1; continue
                pos[0]+=1; m=vec(toks[pos[0]]); pos[0]+=2; c=int(toks[pos[0]]); pos[0]+=2
                terms.append(f"({c} : K) * ({mono(m)})")
            pos[0]+=1; return "("+" + ".join(terms)+")"
        pos[0]+=1; op=toks[pos[0]]; pos[0]+=1
        if op in("br","cn"):
            m=vec(toks[pos[0]]); pos[0]+=2
            return f"({'bk' if op=='br' else 'ck'} ({mono(m)}))"
        a=go()
        if op=="neg": pos[0]+=1; return f"(-{a})"
        b=go(); pos[0]+=1
        return f"({a} {'*' if op=='mul' else '+'} {b})"
    return go()
out='''import Lightlike.TuraevViro.Reflect.RacahBase
import Mathlib.Tactic.FieldSimp

/-!
# Evaluation of the product factors of the q-Racah recurrence

Each factor `fQ0, fNa, ..., fW1` of the cleared recurrence is a `Poly`; here its value at the
environment `(u, p1, p2, p3, p4, q2, q3, Z)` is computed as an ordinary product of brackets
`bk x = x - x⁻¹` and `ck x = x + x⁻¹`. Generated by `scripts/qracah/gen_eval.py`.
-/

set_option maxHeartbeats 0
set_option maxRecDepth 100000

namespace Lightlike.TV.Refl

variable {K : Type*} [Field K]

/-- `x - x⁻¹`. -/
def bk (x : K) : K := x - x⁻¹
/-- `x + x⁻¹`. -/
def ck (x : K) : K := x + x⁻¹

theorem eval_br {E : Env K} (m : Mono) : Poly.eval E (br m) = bk (Mono.eval E m) := by
  simp only [br, eval_add, Poly.eval, bk]
  have : Mono.eval E ⟨-m.e0, -m.e1, -m.e2, -m.e3, -m.e4, -m.e5, -m.e6, -m.e7⟩ = (Mono.eval E m)⁻¹ := by
    simp only [Mono.eval, zpow_neg, mul_inv]
  rw [this]; simp; ring

theorem eval_cn {E : Env K} (m : Mono) : Poly.eval E (cn m) = ck (Mono.eval E m) := by
  simp only [cn, eval_add, Poly.eval, ck]
  have : Mono.eval E ⟨-m.e0, -m.e1, -m.e2, -m.e3, -m.e4, -m.e5, -m.e6, -m.e7⟩ = (Mono.eval E m)⁻¹ := by
    simp only [Mono.eval, zpow_neg, mul_inv]
  rw [this]; simp

/-- The environment `(u, p1, p2, p3, p4, q2, q3, Z)`. -/
def env (u p1 p2 p3 p4 q2 q3 Z : K) : Env K := ⟨u, p1, p2, p3, p4, q2, q3, Z⟩

section Facs
variable {u p1 p2 p3 p4 q2 q3 Z : K} (h0 : u ≠ 0) (h1 : p1 ≠ 0) (h2 : p2 ≠ 0) (h3 : p3 ≠ 0)
  (h4 : p4 ≠ 0) (h5 : q2 ≠ 0) (h6 : q3 ≠ 0) (h7 : Z ≠ 0)
include h0 h1 h2 h3 h4 h5 h6 h7

'''
for k,t in F.items():
    if k in("ftwo",): continue
    # only the simp arguments the expansion of k actually uses (an unused simp argument is a lint warning)
    body=t if k!="fQ012" else "(mul br)"
    first=[k]+(["fQ0","fQ1","fQ2"] if k=="fQ012" else [])
    if "(mul" in body: first.append("eval_mul hE")
    if "(add" in body: first.append("eval_add")
    if "(neg" in body: first.append("eval_neg")
    if "br " in body: first.append("eval_br")
    if "cn " in body: first.append("eval_cn")
    second=["Mono.eval","env"]
    if "br " in body: second.append("bk")
    if "cn " in body: second.append("ck")
    if "[(" in body: second.append("Poly.eval")
    tail="  try ring\n" if "(add" in body else ""
    out+=f'''theorem eval_{k} : Poly.eval (env u p1 p2 p3 p4 q2 q3 Z) {k} = {parse(t)} := by
  have hE : (env u p1 p2 p3 p4 q2 q3 Z).NZ := ⟨h0, h1, h2, h3, h4, h5, h6, h7⟩
  simp only [{", ".join(first)}]
  simp only [{", ".join(second)}]
  field_simp
{tail}
'''
out+="end Facs\n\nend Lightlike.TV.Refl\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
          "Lightlike/TuraevViro/Reflect/RacahEval.lean"), "w").write(out)
