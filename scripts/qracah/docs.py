def insert(text, name):
    if "/-!" in text.split("namespace", 1)[0]:
        return text
    lines = text.split("\n")
    # after the last import line, then a blank line
    last = max(i for i, l in enumerate(lines) if l.startswith("import "))
    return "\n".join(lines[:last + 1] + ["", DOC[name]] + lines[last + 1:])


if __name__ == "__main__":
    for f in sys.argv[1:]:
        name = re.sub(r"^Racah|\.lean$", "", os.path.basename(f))
        s = open(f).read()
        t = insert(s, name)
        open(f, "w").write(t)
        print(f, "changed" if s != t else "unchanged")
