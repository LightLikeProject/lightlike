def fr(x):
    f = Fraction(x)
    return '(%d : ℝ)' % f.numerator if f.denominator == 1 else '(%d/%d : ℝ)' % (f.numerator, f.denominator)
def vecf(t): return '![%s]' % ', '.join(fr(x) for x in t)

